# -*- coding: utf-8 -*-
"""Adapter 所见的运行时端口：只声明 adapter 实际调用的面，不暴露句柄内部结构。"""

from __future__ import annotations

from typing import Any, Awaitable, Callable, Protocol

from ..utils.runs import EventSink, LaunchOptions, ResumeRequest, RunOutcome, RunRequest, SessionInfo, SessionOptions

EventConsumer = EventSink | Callable[[dict[str, Any]], Awaitable[None]]


class RunTicket(Protocol):
    """一次已受理运行的只读视图。"""

    @property
    def run_id(self) -> str: ...

    async def result(self) -> RunOutcome: ...


class CancelResult(Protocol):
    @property
    def cancelled(self) -> bool: ...


class RuntimePort(Protocol):
    """协议 adapter 依赖的运行时接口；实现是 ``runtime.service.RuntimeService``。"""

    #: 进程级 hook（``hooks.models.ProcessHooks``）；本包是叶子层，不引用 hooks。
    @property
    def hooks(self) -> Any: ...

    @property
    def defaults(self) -> LaunchOptions: ...

    async def default_agent_code(self) -> str: ...

    async def has_token(self) -> bool: ...

    async def new_session(self, options: SessionOptions | None = None) -> SessionInfo: ...

    async def session_info(self, code: str | None) -> SessionInfo | None: ...

    async def list_sessions(self) -> list[SessionInfo]: ...

    async def latest_session_code(self) -> str | None: ...

    def has_live_runs(self, code: str) -> bool: ...

    def session_of_run(self, run_id: str) -> str | None: ...

    async def start(self, request: RunRequest, sink: EventConsumer | None = None) -> RunTicket: ...

    async def resume(self, request: ResumeRequest, sink: EventConsumer | None = None) -> RunTicket: ...

    async def prepare(self, session_code: str) -> RunOutcome: ...

    async def describe_agent_config(self, session_code: str) -> Any: ...

    async def list_llms(self, session_code: str) -> Any: ...

    async def describe_config_snapshot(self, session_code: str) -> Any: ...

    async def login(self, token: str) -> None: ...

    async def logout(self) -> None: ...

    async def set_local_declaration(self, code: str, kind: str, value: str) -> None: ...

    async def cancel(self, session_code: str, run_id: str | None = None) -> CancelResult: ...

    async def close(self, session_code: str) -> Any: ...

    async def close_all(self, reason: str = "shutdown", *, grace: float | None = None) -> None: ...
